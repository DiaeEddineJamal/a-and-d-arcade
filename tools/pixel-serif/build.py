# ---------- composed accents ----------
MARKS = {"acute": ("..## .##.", 9), "grave": ("##.. .##.", 9), "diaer": ("##.## ##.##", 9),
         "tilde": (".##.# #.##.", 9), "cedil": (".#. ##.", 0)}


def compose(ch, base, mark):
    top, rows = GL[base]
    mrows, mtop = MARKS[mark][0].split(), MARKS[mark][1]
    w = max(len(rows[0]), len(mrows[0]))
    ox = (len(rows[0]) - len(mrows[0])) // 2
    tops = max(top, mtop)
    bot = min(top - len(rows), mtop - len(mrows))
    grid = [["."] * w for _ in range(tops - bot)]
    for r, line in enumerate(rows):
        for c, v in enumerate(line):
            if v == "#":
                grid[tops - top + r][c] = "#"
    for r, line in enumerate(mrows):
        for c, v in enumerate(line):
            if v == "#":
                grid[tops - mtop + r][c + ox] = "#"
    GL[ch] = (tops, ["".join(g) for g in grid])


for ch, b, m in [("é", "e", "acute"), ("è", "e", "grave"), ("à", "a", "grave"),
                 ("ç", "c", "cedil"), ("ü", "u", "diaer"), ("ö", "o", "diaer"),
                 ("ñ", "n", "tilde")]:
    compose(ch, b, m)

NOTDEF = (9, ["#######", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#.....#", "#######"])


# ---------- font build ----------
def rects(glyph):
    top, rows = glyph
    runs = []
    for r, line in enumerate(rows):
        c = 0
        while c < len(line):
            if line[c] == "#":
                s = c
                while c < len(line) and line[c] == "#":
                    c += 1
                runs.append((s, c, top - r - 1, top - r))
            else:
                c += 1
    merged = []  # merge vertically identical spans into taller rectangles
    for x0, x1, y0, y1 in sorted(runs, key=lambda t: (t[0], t[1], -t[3])):
        for i, m in enumerate(merged):
            if m[0] == x0 and m[1] == x1 and m[2] == y1:
                merged[i] = (x0, x1, y0, m[3])
                break
        else:
            merged.append((x0, x1, y0, y1))
    return merged


def adv(ch):
    return 4 if ch == " " else len(GL[ch][1][0]) + 1


def build():
    chars = sorted(GL, key=ord)
    names = {c: "uni%04X" % ord(c) for c in chars}
    glyphs, metrics = {}, {}
    for ch in [None] + chars:
        n = ".notdef" if ch is None else names[ch]
        g = NOTDEF if ch is None else GL[ch]
        rs = [] if ch == " " else rects(g)
        pen = TTGlyphPen(None)
        for x0, x1, y0, y1 in rs:  # clockwise
            pen.moveTo((x0 * U, y0 * U))
            pen.lineTo((x0 * U, y1 * U))
            pen.lineTo((x1 * U, y1 * U))
            pen.lineTo((x1 * U, y0 * U))
            pen.closePath()
        glyphs[n] = pen.glyph()
        a = 8 if ch is None else adv(ch)
        metrics[n] = (a * U, min([r[0] for r in rs], default=0) * U)
    fb = FontBuilder(1200, isTTF=True)
    fb.setupGlyphOrder([".notdef"] + [names[c] for c in chars])
    fb.setupCharacterMap({ord(c): names[c] for c in chars})
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=1000, descent=-300, lineGap=0)
    fb.setupNameTable({"familyName": "AD Pixel Serif", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=1000, sTypoDescender=-300, sTypoLineGap=0, usWinAscent=1000, usWinDescent=300,
                sxHeight=600, sCapHeight=900, fsType=0)
    fb.setupPost()
    os.makedirs(OUT, exist_ok=True)
    ttf = os.path.join(OUT, "ad-pixel-serif.ttf")
    fb.save(ttf)
    f = TTFont(ttf)
    f.flavor = "woff2"
    f.save(os.path.join(OUT, "ad-pixel-serif.woff2"))
    return ttf


# ---------- preview (bitmaps drawn directly) ----------
INK, BG = (240, 230, 200), (20, 18, 14)


def text_img(s):
    """1 unit/px image of s; 14 rows (10 above baseline, 4 below)."""
    im = Image.new("RGB", (sum(adv(c) for c in s) + 1, 14), BG)
    px, x = im.load(), 0
    for c in s:
        if c != " ":
            top, rows = GL[c]
            for r, line in enumerate(rows):
                for cc, v in enumerate(line):
                    if v == "#":
                        px[x + cc, 10 - top + r] = INK
        x += adv(c)
    return im


def preview(ttf):
    cs = "".join(sorted((c for c in GL if c != " "), key=ord))
    sam = ["A is for her. D is for me.", "Big Box Collection, 1996",
           "The quick brown fox jumps over the lazy dog 0123456789"]
    lines = [(cs[i:i + 26], 6) for i in range(0, len(cs), 26)]
    lines += [(s, k) for s in sam for k in (16 / 12, 32 / 12)]
    ims = []
    for s, k in lines:
        im = text_img(s)
        ims.append(im.resize((round(im.width * k), round(im.height * k)), Image.NEAREST))
    tt = Image.new("RGB", (max(i.width for i in ims), 50), BG)
    ImageDraw.Draw(tt).text((0, 6), "TTF 24px: A is for her. D is for me. Big Box 1996 éñ♥",
                            font=ImageFont.truetype(ttf, 24), fill=INK)
    ims.append(tt)
    W = max(i.width for i in ims) + 40
    out = Image.new("RGB", (W, sum(i.height + 14 for i in ims) + 20), BG)
    y = 10
    for i in ims:
        out.paste(i, (20, y))
        y += i.height + 14
    out.save(os.path.join(HERE, "preview.png"))


if __name__ == "__main__":
    preview(build())
