export type PixelIconName = keyof typeof art;

export default function PixelIcon({ name, className }: { name: PixelIconName; className?: string }) {
  const rows = art[name], rects: string[] = [];
  rows.forEach((row, y) => { for (const run of row.matchAll(/#+/g)) rects.push(`M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`); });
  return <svg className={`px-icon${className ? ` ${className}` : ""}`} viewBox={`0 0 ${rows[0].length} ${rows.length}`} width={rows[0].length * 2} height={rows.length * 2} shapeRendering="crispEdges" aria-hidden="true">
    <path d={rects.join("")} fill="currentColor" />
  </svg>;
}
